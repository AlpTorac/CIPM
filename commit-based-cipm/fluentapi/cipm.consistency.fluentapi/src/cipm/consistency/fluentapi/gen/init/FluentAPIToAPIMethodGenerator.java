package cipm.consistency.fluentapi.gen.init;

import org.eclipse.emf.ecore.EClass;
import org.eclipse.emf.ecore.EOperation;

import cipm.consistency.fluentapi.gen.FluentAPIGenerationUtil;
import cipm.consistency.fluentapi.gen.methods.FluentAPIMethodsUtil;

public class FluentAPIToAPIMethodGenerator {
	private static final String toAPIMethodName = "toAPI";
	private static final String toAPIMethodDocumentation = "Swaps from this initialisation instance to the API, which created it. This method is currently the same as this.getRootAPI(). Its purpose is to isolate the use of this.getRootAPI(), which is a getter method that is generated by EMF.";

	private static final String toAPIMethodBodyTemplate = FluentAPIMethodsUtil.joinLOC("return this.getRootAPI()");

	public EOperation generateToAPIMethod(EClass rootAPIEClass) {
		return FluentAPIGenerationUtil.generateEOperationWithBodyAndDocumentation(toAPIMethodName, rootAPIEClass,
				toAPIMethodBodyTemplate, toAPIMethodDocumentation);
	}
}
